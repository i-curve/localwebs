export type Language = 'en' | 'zh-CN';
const saved = localStorage.getItem('localwebs-language');
export const language = ref<Language>(
  saved === 'en' || saved === 'zh-CN' ? saved : navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en'
);
watchEffect(() => {
  document.documentElement.lang = language.value;
  localStorage.setItem('localwebs-language', language.value);
});

